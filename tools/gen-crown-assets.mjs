/**
 * Generate src/client/crownAssets.ts from assets/crown_*.svg — the ten crown
 * tier artworks are inlined into the client bundle (the tsdown browser half
 * has no asset pipeline, everything ships inside lib/client.js).
 *
 * Usage: node tools/gen-crown-assets.mjs
 * The output file is checked in; rerun whenever an asset changes.
 * @module dsh-games/tools/gen-crown-assets
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS = join(ROOT, 'assets')
const OUT = join(ROOT, 'src', 'client', 'crownAssets.ts')

/** Tier ids in ladder order (must match src/crowns.ts CROWN_LEVELS ids). */
const TIER_IDS = [
  'bronze',
  'silver',
  'gold',
  'platinum',
  'amethyst',
  'magic-bronze',
  'magic-silver',
  'magic-gold',
  'magic-platinum',
  'magic-amethyst',
]

const files = new Map(
  TIER_IDS.map((id) => [`crown_${id.replace('-', '_')}.svg`, id]),
)

const entries = []
for (const [fileName, id] of files) {
  const source = readFileSync(join(ASSETS, fileName), 'utf8')
  if (!/<svg\b/.test(source)) throw new Error(`${fileName}: not an SVG file`)
  entries.push([id, source])
}

const body = entries
  .map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)},`)
  .join('\n')

const header = `/**
 * @generated by tools/gen-crown-assets.mjs — do not edit by hand.
 * Inline SVG artwork for the ten crown tiers, sourced from assets/crown_*.svg
 * (keys match the CROWN_LEVELS ids in src/crowns.ts).
 */
export const CROWN_SVGS: Readonly<Record<string, string>> = {
${body}
}
`

writeFileSync(OUT, header)
console.log(`[gen-crown-assets] wrote ${OUT} (${entries.length} tiers, ${header.length} bytes)`)
